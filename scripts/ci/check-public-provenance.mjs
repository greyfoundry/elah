import { execFile } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);
const scannerFiles = new Set([
  'scripts/ci/check-public-provenance.mjs',
  'scripts/ci/check-public-provenance.test.mjs',
]);
const markers = [
  { label: 'ChatGPT', pattern: new RegExp(['chat', 'gpt'].join(''), 'i') },
  { label: 'OpenAI', pattern: new RegExp(['open', 'ai'].join(''), 'i') },
  { label: 'Codex', pattern: new RegExp(['code', 'x'].join(''), 'i') },
  { label: 'Claude', pattern: new RegExp(['clau', 'de'].join(''), 'i') },
  { label: 'Anthropic', pattern: new RegExp(['anthro', 'pic'].join(''), 'i') },
  {
    label: 'generated by AI',
    pattern: new RegExp(`generated\\s+by\\s+(?:an?\\s+)?(?:${['ai', 'chatgpt', 'openai', 'codex', 'claude'].join('|')})`, 'i'),
  },
  { label: 'AI-generated', pattern: /\bAI[- ]generated\b/i },
];

async function trackedFiles(root) {
  const { stdout } = await execFileAsync('git', ['ls-files', '-z'], {
    cwd: root,
    encoding: 'buffer',
    maxBuffer: 16 * 1024 * 1024,
  });
  return stdout
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .map((file) => file.replaceAll('\\', '/'))
    .sort();
}

export async function checkPublicProvenance(root = process.cwd()) {
  const diagnostics = [];
  for (const file of await trackedFiles(root)) {
    if (scannerFiles.has(file)) {
      continue;
    }
    const contents = await readFile(path.join(root, file));
    if (contents.includes(0)) {
      continue;
    }
    const lines = contents.toString('utf8').split(/\r?\n/);
    for (const [index, line] of lines.entries()) {
      for (const marker of markers) {
        if (marker.pattern.test(line)) {
          diagnostics.push(`${file}:${index + 1}: public provenance marker is forbidden: ${marker.label}`);
        }
      }
    }
  }
  return diagnostics.sort();
}

async function main() {
  const diagnostics = await checkPublicProvenance(process.argv[2] ?? process.cwd());
  if (diagnostics.length > 0) {
    process.stderr.write(`Public provenance violations:\n${diagnostics.map((item) => `- ${item}`).join('\n')}\n`);
    process.exitCode = 1;
    return;
  }
  process.stdout.write('Public provenance is clean.\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
